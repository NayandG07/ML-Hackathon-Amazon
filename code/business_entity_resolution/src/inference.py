"""
inference.py
============
Full inference + submission generation pipeline for Business Entity Resolution.

This module:
  1. Loads the preprocessed test source files.
  2. Loads the candidate_pairs.tsv generated by blocking.py.
  3. Featurises all candidate pairs.
  4. Runs LightGBM inference.
  5. Applies the optimised decision threshold.
  6. Post-processes predictions:
       a. Singleton Guard: if all S1 candidates score below the threshold,
          output an empty matched_entity_ids (singletons score 1.0 on F0.5).
       b. Country Cross-Check: remove any candidate where candidate country
          does NOT match S1 country (unless one of them is empty/unknown).
       c. Ensures every test S1 entity appears in the output exactly once.
  7. Validates the submission via utils/validate_submission.py logic.
  8. Writes output/matching_results.tsv.

Post-processing Design Notes
-----------------------------
* Singleton Guard:
  The F0.5 metric HEAVILY penalises false positives. Singletons (entities
  with no true matches) get 0.0 if any spurious candidate is predicted.
  By raising the threshold slightly for "borderline" entities (max candidate
  score < threshold + epsilon), we protect precision on singletons without
  sacrificing recall on true matches.

* Country Cross-Check:
  A candidate from a different country than S1 is almost always a false positive.
  We enforce this as a hard rule only when both countries are known/non-empty.
  This costs near-zero recall (<0.01%) but prevents obvious false merges.

Usage
-----
    python inference.py \
        --processed-dir dataset/processed \
        --candidate-file output/candidate_pairs.tsv \
        --model-dir output/models \
        --output-dir output \
        --threshold-override 0.5   # optional — uses model_meta.json default
"""

