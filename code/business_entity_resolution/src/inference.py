def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--processed-dir", default="dataset/processed")
    parser.add_argument("--candidate-file", default="output/candidate_pairs.tsv")
    parser.add_argument("--model-dir", default="output/models")
    parser.add_argument("--output-dir", default="output")
    parser.add_argument("--threshold-override", type=float, default=None,
                        help="Override the decision threshold from model_meta.json")
    parser.add_argument("--max-matches-per-entity", type=int, default=5,
                        help="Max candidates to predict per S1 entity (top-K by score). "
                             "Ground truth median=4, max=11. Default 5.")
    parser.add_argument("--entity-batch-size", type=int, default=10_000,
                        help="Entities per inference batch. 10K × ~100 cands = ~1M pairs "
                             "→ ~150 MB numpy RAM. Reduce if OOM.")
    parser.add_argument("--min-name-sim", type=float, default=0.40,
                        help="Minimum name_token_sort_ratio for Dual-Agreement Gate (default 0.40)")
    parser.add_argument("--min-addr-sim", type=float, default=0.25,
                        help="Minimum addr_token_sort_ratio for Dual-Agreement Gate (default 0.25)")
    parser.add_argument("--no-country-filter", action="store_true")
    parser.add_argument("--embed-scores-file", default=None,
                        help="Optional parquet file with precomputed (s1_id, cand_id, embed_cosine_sim) columns."
                             " When provided, fills the embed_cosine_sim feature for better accuracy.")
    parser.add_argument("--model-name", default="lgbm_model.pkl",
                        help="Model filename inside model-dir (default lgbm_model.pkl)")
    parser.add_argument("--embeddings-dir", default=None,
                        help="Directory containing test_s1_embeds.npy and test_s23_embeds.npy for fast on-the-fly scoring")
    args = parser.parse_args()

    proc_dir = Path(args.processed_dir)
    model_dir = Path(args.model_dir)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    with StageTimer("Inference Pipeline"):
        model_path = model_dir / args.model_name
        log.info(f"Loading model from [highlight]{model_path}[/highlight] …")
        with open(str(model_path), "rb") as f:
            model = pickle.load(f)

        meta_name = "model_meta_v2.json" if "v2" in args.model_name else "model_meta.json"
        meta_path = model_dir / meta_name
        if meta_path.exists():
            with open(str(meta_path)) as f:
                meta = json.load(f)
            threshold = args.threshold_override or meta.get("threshold", 0.50)
        else:
            threshold = args.threshold_override or 0.50
        log.info(f"Decision threshold       : [metric]{threshold:.4f}[/metric]")
        log.info(f"Max matches per entity   : [metric]{args.max_matches_per_entity}[/metric]")
        log.info(f"Entity batch size        : [metric]{args.entity_batch_size:,}[/metric]")
        log.info(f"Dual-Gate min name sim   : [metric]{args.min_name_sim:.2f}[/metric]")
        log.info(f"Dual-Gate min addr sim   : [metric]{args.min_addr_sim:.2f}[/metric]")

        sysinfo(show=True)

        log.info("Loading preprocessed test data …")
        s1_df = pl.read_parquet(str(proc_dir / "test_s1.parquet"))
        s2_df = pl.read_parquet(str(proc_dir / "test_s2.parquet"))
        s3_df = pl.read_parquet(str(proc_dir / "test_s3.parquet"))
        s23_df = pl.concat([s2_df, s3_df])

        test_s1_ids = s1_df["entity_id"].to_list()
        log.info(f"  Test S1 entities: [highlight]{len(test_s1_ids):,}[/highlight]")

        log.info(f"Loading candidates from [highlight]{args.candidate_file}[/highlight] …")
        candidates_df = pl.read_csv(
            args.candidate_file, separator="\t",
            null_values=[""], infer_schema_length=100,
        )

        # Load precomputed embedding scores if provided
        embed_scores_lookup = None
        if args.embed_scores_file and Path(args.embed_scores_file).exists():
            log.info(f"Loading embedding scores from [highlight]{args.embed_scores_file}[/highlight] …")
            embed_df = pl.read_parquet(args.embed_scores_file)
            embed_scores_lookup = {
                (row["s1_id"], row["cand_id"]): row["embed_cosine_sim"]
                for row in embed_df.iter_rows(named=True)
            }
            log.info(f"  Loaded [highlight]{len(embed_scores_lookup):,}[/highlight] embedding similarity pairs")

        # Load mmap embeddings for on-the-fly cosine calculation if provided
        embed_data = None
        if args.embeddings_dir and Path(args.embeddings_dir).exists():
            emb_dir = Path(args.embeddings_dir)
            s1_f = emb_dir / "test_s1_embeds.npy"
            s23_f = emb_dir / "test_s23_embeds.npy"
            if s1_f.exists() and s23_f.exists():
                log.info(f"Loading mmap embeddings from [highlight]{emb_dir}[/highlight] …")
                s1_emb = np.load(str(s1_f), mmap_mode="r")
                s1_ids = np.load(str(emb_dir / "test_s1_ids.npy"), allow_pickle=True)
                s23_emb = np.load(str(s23_f), mmap_mode="r")
                s23_ids = np.load(str(emb_dir / "test_s23_ids.npy"), allow_pickle=True)
                s1_idx = {eid: i for i, eid in enumerate(s1_ids)}
                s23_idx = {eid: i for i, eid in enumerate(s23_ids)}
                embed_data = (s1_emb, s23_emb, s1_idx, s23_idx)
                log.info(f"  Ready for on-the-fly cosine scoring ({len(s1_ids):,} S1, {len(s23_ids):,} S23)")

        scores_path = str(out_dir / "scores_raw.parquet")
        predictions = run_inference(
            candidates_df, s1_df, s23_df, model,
            threshold=threshold,
            apply_country_filter=not args.no_country_filter,
            entity_batch_size=args.entity_batch_size,
            max_matches_per_entity=args.max_matches_per_entity,
            scores_save_path=scores_path,
            min_save_threshold=0.40,
            min_name_sim=args.min_name_sim,
            min_addr_sim=args.min_addr_sim,
            embed_scores_lookup=embed_scores_lookup,
            embed_data=embed_data,
        )

        for s1_id in test_s1_ids:
            predictions.setdefault(s1_id, [])

        results_df = build_matching_results(predictions, test_s1_ids)

    out_path = out_dir / "matching_results.tsv"
    results_df.write_csv(str(out_path), separator="\t", quote_style="never")
    log.info(f"Saved → [highlight]{out_path}[/highlight]")

    n_singletons = results_df.filter(pl.col("matched_entity_ids") == "").height
    print_metrics("Submission File Summary", {
        "Total rows":       f"{len(results_df):,}",
        "With matches":     f"{len(results_df) - n_singletons:,}",
        "Singletons":       f"{n_singletons:,}",
        "Output path":      str(out_path),
    })
    print_done("Inference complete — run validate_submission.py to check format!")


if __name__ == "__main__":
    main()
